'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const src=fs.readFileSync('interaction-surfaces.js','utf8');
const shell=fs.readFileSync('index.html','utf8');
const sw=fs.readFileSync('sw.js','utf8');
assert.match(shell,/interaction-surfaces\.js\?v=/,'interaction repair must load in production');
assert.match(sw,/\.\/interaction-surfaces\.js/,'interaction repair must be available offline');
assert.match(src,/dedupeId\('followupInbox'\)|\[\s*'followupInbox',\s*'peopleMemory',\s*'ask'/,'duplicate second-brain sections must be removed');
assert.match(src,/\.person-card/,'People cards must have an explicit interaction path');
assert.match(src,/openAsk\(person\.dataset\.person/,'People cards must open grounded recall for that person');
assert.match(src,/\.followup-tabs button\[data-follow\]/,'follow-up tabs must be explicitly delegated');
assert.match(src,/renderFollowups\(tab\.dataset\.follow\)/,'follow-up tabs must re-render their selected inbox');
assert.match(src,/dataset\.offsetMs\s*=\s*String\(x\.startMs\s*\|\|\s*0\)/,'follow-up rows must retain exact source offsets');
assert.match(src,/\.insight-open/,'meeting cards must have a guaranteed open interaction');
assert.match(src,/\.insight-card \.insight-top/,'meeting headers must also be clickable');
assert.match(src,/SynapProvenance\?\.openSource/,'interactive surfaces must use provenance source navigation');
assert.doesNotMatch(src,/startButton|stopButton|connectButton|gatt|bluetooth/i,'interaction repair must not own pendant recording controls');
console.log('PASS: People, follow-up inbox and meetings are single-instance, interactive and source-linked');
